// Builds lib/fonts/lato-data.ts: the two Lato font files the review card PDF
// embeds, each compressed and written as text so that they travel inside the
// app's own code (a serverless function cannot rely on reading a font file
// from disk).
//
// Lato is open source, under the SIL Open Font License 1.1 (lib/fonts/Lato-OFL.txt).
// The files are embedded whole and unmodified. Get them from
//   https://github.com/google/fonts/tree/main/ofl/lato   (Lato-Regular.ttf, Lato-Bold.ttf)
// and run:
//   node scripts/build-card-fonts.mjs <folder holding the two .ttf files>
import { readFileSync, writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2];
if (!dir) { console.error('Usage: node scripts/build-card-fonts.mjs <folder with Lato-Regular.ttf and Lato-Bold.ttf>'); process.exit(1); }
const one = (file) => {
  const raw = readFileSync(join(dir, file));
  const packed = deflateSync(raw, { level: 9 });
  return { file, length: raw.length, sha256: createHash('sha256').update(raw).digest('hex'), base64: packed.toString('base64') };
};
const fonts = { regular: one('Lato-Regular.ttf'), bold: one('Lato-Bold.ttf') };
const lines = (b64) => b64.match(/.{1,160}/g).map((l) => `  '${l}',`).join('\n');
const out = `// GENERATED by scripts/build-card-fonts.mjs. Do not edit by hand.
//
// Lato Regular and Lato Bold, whole and unmodified, each deflate-compressed and
// written as base64. Copyright (c) 2010-2014 by tyPoland Lukasz Dziedzic, with
// Reserved Font Name "Lato". Licensed under the SIL Open Font License,
// Version 1.1: see lib/fonts/Lato-OFL.txt.
/* eslint-disable */
export interface PackedFont { file: string; /** Bytes of the font file before compression. */ length: number; /** SHA-256 of the font file, so it can be checked against the published one. */ sha256: string; /** The font file, deflate-compressed, as base64 in pieces. */ deflatedBase64: string[] }

export const LATO_REGULAR: PackedFont = { file: '${fonts.regular.file}', length: ${fonts.regular.length}, sha256: '${fonts.regular.sha256}', deflatedBase64: [
${lines(fonts.regular.base64)}
] };

export const LATO_BOLD: PackedFont = { file: '${fonts.bold.file}', length: ${fonts.bold.length}, sha256: '${fonts.bold.sha256}', deflatedBase64: [
${lines(fonts.bold.base64)}
] };
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'fonts', 'lato-data.ts');
writeFileSync(target, out);
console.log(`wrote ${target}: regular ${fonts.regular.length} bytes, bold ${fonts.bold.length} bytes`);
